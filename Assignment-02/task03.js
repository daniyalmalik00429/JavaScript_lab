
let num1 = 8;
let num2 = 4;

let operator = "+";

if (operator === "+") {
    console.log("Sum:", num1 + num2);
} else if (operator === "-") {
    console.log("Difference:", num1 - num2);
}

operator = "-";

if (operator === "+") {
    console.log("Sum:", num1 + num2);
} else if (operator === "-") {
    console.log("Difference:", num1 - num2);
}
